// Bundles the generated NPC portrait plates into the client as data URLs.
// Source art lives in art/npc/<npcId>/<expression>.png; run
//   node scripts/vendor-portraits.mjs
// after regenerating the plates.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const tags = [
  "neutral",
  "smile",
  "shy",
  "worried",
  "sad",
  "surprised",
  "thinking",
  "look_away",
];
const npcs = ["linwanqing", "hunter"];
const sources = {};

for (const npc of npcs) {
  sources[npc] = {};
  for (const tag of tags) {
    const png = await readFile(join(root, "art", "npc", npc, `${tag}.png`));
    sources[npc][tag] = `data:image/png;base64,${png.toString("base64")}`;
  }
}

const out = `// Generated by scripts/vendor-portraits.mjs from art/npc/*. Do not edit.
export const PortraitTags = ${JSON.stringify(tags)} as const;
export type PortraitTag = (typeof PortraitTags)[number];
export const PortraitSources: Record<string, Record<PortraitTag, string>> = ${JSON.stringify(
  sources,
  null,
  2,
)};
`;
const target = join(root, "src", "client", "npc", "sources.ts");
await mkdir(dirname(target), { recursive: true });
await writeFile(target, out, "utf8");
console.log(`wrote ${target} (${out.length} chars)`);