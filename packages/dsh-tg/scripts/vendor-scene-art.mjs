// Regenerates src/client/scene/{sources,art}.ts from the city scene viewer.
// Usage: node scripts/vendor-scene-art.mjs [path-to-city-scenes]
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const sceneDir = resolve(here, "../src/client/scene");
const source = resolve(
  process.argv[2] ?? "D:/code/Web/public/city-scenes",
).replaceAll("\\", "/");

mkdirSync(sceneDir, { recursive: true });

const sources = readFileSync(join(source, "scene-images.js"), "utf8")
  .replace(/^\uFEFF/, "")
  .slice(readFileSync(join(source, "scene-images.js"), "utf8").indexOf("window.CitySceneSources"))
  .replace(
    "window.CitySceneSources = {",
    "export const CitySceneSources: Record<string, string> = {",
  );
writeFileSync(
  join(sceneDir, "sources.ts"),
  "// Generated by scripts/vendor-scene-art.mjs — 176x88 RGB plates, base64.\n" +
    sources,
  "utf8",
);

const art = readFileSync(join(source, "art.js"), "utf8")
  .replace(/^\uFEFF/, "")
  .replace(/^\(\(\) => \{\r?\n/, "")
  .replace(/\r?\n\}\)\(\);\s*$/, "")
  .split("window.CitySceneSources")
  .join("CitySceneSources")
  .replace(
    /^\s*window\.CitySceneArt = .*$/m,
    "export { groups, times, scenes, makeRenderer, baseFrame, drawDots, outputWidth, outputHeight };",
  );
writeFileSync(
  join(sceneDir, "art.ts"),
  "// @ts-nocheck\n// Generated by scripts/vendor-scene-art.mjs from art.js (dot-matrix renderer).\n" +
    'import { CitySceneSources } from "./sources";\n\n' +
    art,
  "utf8",
);

console.log(`vendored scene art from ${source}`);